import streamlit as st

from utils.theme import inject_theme
from utils.data import load_games, load_teams
from utils.elo import compute_elo_timeline

inject_theme()

st.title("Predictions")
st.caption("Win probabilities generated by our Elo rating model, updated after every game.")

teams = load_teams()
games = load_games()

elo_entering_week, current_elo, predictions = compute_elo_timeline(games, teams)

if predictions.empty:
    st.info("No games on the schedule yet.")
    st.stop()

id_to_school = dict(zip(teams["TeamID"], teams["School"]))

weeks = sorted(predictions["Week"].dropna().unique())
week = st.selectbox("Week", weeks)

week_games = predictions[predictions["Week"] == week]

for _, g in week_games.iterrows():
    home_name = id_to_school.get(g["HomeID"], g["HomeID"])
    away_name = id_to_school.get(g["AwayID"], g["AwayID"])

    home_pct = round(g["HomeWinProb"] * 100)
    away_pct = 100 - home_pct

    st.markdown(f"**{home_name}** ({home_pct}%) vs **{away_name}** ({away_pct}%)")
    st.progress(home_pct / 100)

    if g["Status"] == "Final":
        result = f"Final: {home_name} {int(g['HomeScore'])} - {away_name} {int(g['AwayScore'])}"
        if g["Upset"]:
            result += "  🚨 Upset"
        st.caption(result)

    st.divider()